-- HealthDekho schema (spec section 5.2).
-- Claim tables (spec 5.4) are future scope (FE-1) and are deliberately not created.
-- premium_payment is kept as the spec's database design defines it; no application code writes to it
-- since FR-4 (premium payments) was removed from scope.
-- Money NUMERIC(19,2), dates DATE, audit timestamps TIMESTAMP WITH TIME ZONE (spec 5.1).

CREATE TABLE customer (
    customer_id    BIGINT GENERATED BY DEFAULT AS IDENTITY,
    email          VARCHAR(255)             NOT NULL,
    password_hash  VARCHAR(255)             NOT NULL,
    full_name      VARCHAR(150)             NOT NULL,
    date_of_birth  DATE                     NOT NULL,
    phone          VARCHAR(20)              NOT NULL,
    status         VARCHAR(20)              NOT NULL DEFAULT 'ACTIVE',
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    updated_at     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT pk_customer PRIMARY KEY (customer_id),
    CONSTRAINT uq_customer_email UNIQUE (email),
    CONSTRAINT ck_customer_date_of_birth CHECK (date_of_birth <= CURRENT_DATE),
    CONSTRAINT ck_customer_status CHECK (status IN ('ACTIVE', 'INACTIVE'))
);
CREATE INDEX ix_customer_status ON customer (status);

CREATE TABLE insurance_product (
    product_id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    product_code       VARCHAR(30)              NOT NULL,
    policy_name        VARCHAR(150)             NOT NULL,
    policy_type        VARCHAR(30)              NOT NULL,
    term_months        INTEGER                  NOT NULL,
    premium_frequency  VARCHAR(20)              NOT NULL,
    premium_amount     NUMERIC(19, 2)           NOT NULL,
    sum_insured        NUMERIC(19, 2)           NOT NULL,
    min_entry_age      INTEGER                  NOT NULL,
    max_entry_age      INTEGER                  NOT NULL,
    active             BOOLEAN                  NOT NULL DEFAULT TRUE,
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    updated_at         TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT pk_insurance_product PRIMARY KEY (product_id),
    CONSTRAINT uq_insurance_product_code UNIQUE (product_code),
    CONSTRAINT ck_insurance_product_type CHECK (policy_type IN ('TERM', 'HEALTH', 'SAVINGS')),
    CONSTRAINT ck_insurance_product_frequency CHECK (premium_frequency IN ('MONTHLY', 'QUARTERLY', 'HALF_YEARLY', 'YEARLY')),
    CONSTRAINT ck_insurance_product_term CHECK (term_months > 0),
    CONSTRAINT ck_insurance_product_premium CHECK (premium_amount > 0),
    CONSTRAINT ck_insurance_product_sum_insured CHECK (sum_insured > 0),
    CONSTRAINT ck_insurance_product_ages CHECK (min_entry_age >= 0 AND min_entry_age <= max_entry_age)
);
CREATE INDEX ix_insurance_product_active ON insurance_product (active);

CREATE TABLE customer_policy (
    policy_id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    policy_number          VARCHAR(30)              NOT NULL,
    customer_id            BIGINT                   NOT NULL,
    product_id             BIGINT                   NOT NULL,
    start_date             DATE                     NOT NULL,
    maturity_date          DATE                     NOT NULL,
    premium_frequency      VARCHAR(20)              NOT NULL,
    premium_amount         NUMERIC(19, 2)           NOT NULL,
    sum_insured            NUMERIC(19, 2)           NOT NULL,
    total_premium_payable  NUMERIC(19, 2)           NOT NULL,
    status                 VARCHAR(20)              NOT NULL DEFAULT 'ACTIVE',
    created_at             TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    updated_at             TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT pk_customer_policy PRIMARY KEY (policy_id),
    CONSTRAINT uq_customer_policy_number UNIQUE (policy_number),
    -- Duplicate rule: one registration per customer and product.
    CONSTRAINT uq_customer_policy_customer_product UNIQUE (customer_id, product_id),
    CONSTRAINT fk_customer_policy_customer FOREIGN KEY (customer_id) REFERENCES customer (customer_id),
    CONSTRAINT fk_customer_policy_product FOREIGN KEY (product_id) REFERENCES insurance_product (product_id),
    CONSTRAINT ck_customer_policy_dates CHECK (maturity_date > start_date),
    CONSTRAINT ck_customer_policy_frequency CHECK (premium_frequency IN ('MONTHLY', 'QUARTERLY', 'HALF_YEARLY', 'YEARLY')),
    CONSTRAINT ck_customer_policy_premium CHECK (premium_amount > 0),
    CONSTRAINT ck_customer_policy_sum_insured CHECK (sum_insured > 0),
    CONSTRAINT ck_customer_policy_total CHECK (total_premium_payable > 0),
    CONSTRAINT ck_customer_policy_status CHECK (status IN ('ACTIVE', 'FULLY_PAID'))
);
CREATE INDEX ix_customer_policy_customer ON customer_policy (customer_id);
CREATE INDEX ix_customer_policy_status ON customer_policy (status);

CREATE TABLE premium_installment (
    installment_id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    policy_id              BIGINT                   NOT NULL,
    installment_number     INTEGER                  NOT NULL,
    due_date               DATE                     NOT NULL,
    grace_period_end_date  DATE                     NOT NULL,
    scheduled_amount       NUMERIC(19, 2)           NOT NULL,
    paid_amount            NUMERIC(19, 2)           NOT NULL DEFAULT 0,
    payment_status         VARCHAR(20)              NOT NULL DEFAULT 'PENDING',
    created_at             TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    updated_at             TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT pk_premium_installment PRIMARY KEY (installment_id),
    CONSTRAINT uq_premium_installment_policy_number UNIQUE (policy_id, installment_number),
    CONSTRAINT fk_premium_installment_policy FOREIGN KEY (policy_id) REFERENCES customer_policy (policy_id),
    CONSTRAINT ck_premium_installment_number CHECK (installment_number > 0),
    CONSTRAINT ck_premium_installment_grace CHECK (grace_period_end_date >= due_date),
    CONSTRAINT ck_premium_installment_scheduled CHECK (scheduled_amount > 0),
    CONSTRAINT ck_premium_installment_paid CHECK (paid_amount >= 0 AND paid_amount <= scheduled_amount),
    CONSTRAINT ck_premium_installment_status CHECK (payment_status IN ('PENDING', 'PARTIALLY_PAID', 'PAID', 'OVERDUE'))
);
CREATE INDEX ix_premium_installment_due_date ON premium_installment (due_date);

CREATE TABLE premium_payment (
    payment_id             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    installment_id         BIGINT                   NOT NULL,
    transaction_reference  VARCHAR(40)              NOT NULL,
    payment_date           DATE                     NOT NULL,
    amount_paid            NUMERIC(19, 2)           NOT NULL,
    penalty_amount         NUMERIC(19, 2)           NOT NULL DEFAULT 0,
    payment_method         VARCHAR(20)              NOT NULL,
    created_at             TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT pk_premium_payment PRIMARY KEY (payment_id),
    CONSTRAINT uq_premium_payment_transaction_reference UNIQUE (transaction_reference),
    CONSTRAINT fk_premium_payment_installment FOREIGN KEY (installment_id) REFERENCES premium_installment (installment_id),
    CONSTRAINT ck_premium_payment_amount CHECK (amount_paid > 0),
    CONSTRAINT ck_premium_payment_penalty CHECK (penalty_amount >= 0),
    CONSTRAINT ck_premium_payment_method CHECK (payment_method IN ('UPI', 'CARD', 'NET_BANKING'))
);
CREATE INDEX ix_premium_payment_installment ON premium_payment (installment_id);
CREATE INDEX ix_premium_payment_date ON premium_payment (payment_date);

CREATE TABLE ai_recommendation_request (
    recommendation_request_id  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    customer_id                BIGINT                   NOT NULL,
    insurance_goals            VARCHAR(500)             NOT NULL,
    preferred_term             VARCHAR(30),
    preferred_policy_type      VARCHAR(30),
    calculated_age             INTEGER                  NOT NULL,
    model_name                 VARCHAR(100)             NOT NULL,
    model_version              VARCHAR(100)             NOT NULL,
    prompt_version             VARCHAR(30)              NOT NULL,
    requested_at               TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT pk_ai_recommendation_request PRIMARY KEY (recommendation_request_id),
    CONSTRAINT fk_ai_recommendation_request_customer FOREIGN KEY (customer_id) REFERENCES customer (customer_id),
    CONSTRAINT ck_ai_recommendation_request_age CHECK (calculated_age >= 0)
);
CREATE INDEX ix_ai_recommendation_request_customer ON ai_recommendation_request (customer_id);
CREATE INDEX ix_ai_recommendation_request_requested_at ON ai_recommendation_request (requested_at);

CREATE TABLE ai_recommendation_item (
    recommendation_item_id     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    recommendation_request_id  BIGINT       NOT NULL,
    product_id                 BIGINT       NOT NULL,
    rank_order                 INTEGER      NOT NULL,
    recommendation_reason      VARCHAR(500) NOT NULL,
    suitability                VARCHAR(10)  NOT NULL,
    selected_for_registration  BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT pk_ai_recommendation_item PRIMARY KEY (recommendation_item_id),
    CONSTRAINT uq_ai_recommendation_item_request_product UNIQUE (recommendation_request_id, product_id),
    CONSTRAINT fk_ai_recommendation_item_request FOREIGN KEY (recommendation_request_id) REFERENCES ai_recommendation_request (recommendation_request_id),
    CONSTRAINT fk_ai_recommendation_item_product FOREIGN KEY (product_id) REFERENCES insurance_product (product_id),
    CONSTRAINT ck_ai_recommendation_item_rank CHECK (rank_order > 0),
    CONSTRAINT ck_ai_recommendation_item_suitability CHECK (suitability IN ('HIGH', 'MEDIUM', 'LOW'))
);
CREATE INDEX ix_ai_recommendation_item_product ON ai_recommendation_item (product_id);

